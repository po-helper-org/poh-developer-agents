"""Доведение PR по замечаниям ревью — круг правок (точка передачи H3→H4).

PR-Agent публикует ревью и останавливается: доводить код до соответствия
замечаниям — не его работа. До сих пор это делал человек, и именно здесь контур
переставал быть автономным.

Круг ведёт тот же цикл, который уже владеет состоянием задачи: он стоит в фазе
`pr-review` и ждёт. Отдельный сервис потребовал бы второй копии всего — клона,
раннера, прогона тестов, пуша — и ещё одного канала докладов обратно.

Признак «замечаний нет» — ПУСТОЙ ДИФФ после прогона агента.

Это главное решение модуля. Разметку ревью можно было бы разбирать и считать,
какие пункты блокирующие, — но тогда контур зависел бы от формата чужого
инструмента, который меняется без предупреждения. Вместо этого агенту отдаётся
текст ревью и правило «исправь то, что требует исправления; если по существу
нечего — не меняй ничего». Пустой дифф — это его вердикт, выраженный делом.

Модуль намеренно чистый: ни сети, ни Temporal, ни GitHub.
"""

import os

# Потолок кругов. Правило R8 протокола: доведение — не разработка, у него есть
# предел. Агент, который третий раз не сходится с ревью, дальше не сойдётся —
# он спорит с ним, а не исправляет. Такой PR уходит человеку.
DEFAULT_MAX_ROUNDS = 3

# Метка очереди к человеку из общего словаря контура.
NEEDS_HUMAN_PR = "needs-human:pr"

# Команда, которой круг просит PR-Agent перепроверить. Комментарий от живого
# пользователя события порождает, поэтому цикл пишет её своим токеном.
REVIEW_COMMAND = "/review"

# Файл, в который агент пишет разбор замечаний. Существует потому, что пустой
# дифф сам по себе ничего не объясняет: «нечего исправлять» и «прогон сломался»
# выглядят одинаково. Разбор публикуется комментарием — отклонённое замечание
# должно быть видно человеку вместе с причиной.
VERDICT_FILE = ".verdict.md"


def max_rounds() -> int:
    raw = os.environ.get("PR_FIX_MAX_ROUNDS", "").strip()
    try:
        value = int(raw) if raw else DEFAULT_MAX_ROUNDS
    except ValueError:
        return DEFAULT_MAX_ROUNDS
    return value if value > 0 else DEFAULT_MAX_ROUNDS


def enabled() -> bool:
    """Пусто — включено. Явное `0` оставляет PR человеку сразу после ревью."""
    return os.environ.get("PR_FIX_ENABLED", "").strip().lower() not in {"0", "false", "no", "off"}


def task_slug(repo: str, pr_number: int) -> str:
    return f"prfix-{repo.replace('/', '__')}-{pr_number}"


def build_task(pr_number: int, *, review: str, round_number: int, max_rounds_: int) -> str:
    """Постановка круга правок.

    Замечания отдаются ДОСЛОВНО: пересказ своими словами — лишнее звено, в
    котором теряется именно то, что ревьюер счёл важным.
    """
    return f"""# Довести PR #{pr_number} по замечаниям ревью

Круг {round_number} из {max_rounds_}.

## Замечания ревьюера

{review.strip() or "(текст ревью пуст)"}

## Что делать

Сначала **реши по каждому замечанию, стоит ли оно правки**. Автоматический
ревьюер находит к чему придраться всегда — это его работа. Твоя работа —
отличить то, что улучшит код, от того, что просто сожжёт круг.

**Исправлять:** неверное поведение, необработанный случай, расхождение с
требованиями задачи, отсутствующий тест на новую логику, настоящая уязвимость.

**Отклонять:**
- стилистические придирки, не меняющие поведения;
- требования того, что уже сделано ВНЕ диффа — ревью видит только дифф и
  регулярно требует существующего; проверь по коду, прежде чем исправлять;
- пожелания «на будущее» и архитектурные советы, не относящиеся к задаче этого
  PR — им место в отдельной задаче, а не здесь;
- повтор замечания, отклонённого на прошлом круге, без новых доводов.

Затем:

1. **Исправь принятое.** Только в границах уже написанного в этом PR. Это
   доведение, а не разработка: новая функциональность сюда не добавляется.
2. **Если принятого нет — НЕ МЕНЯЙ НИЧЕГО.** Пустой результат это законный
   исход круга. Не правь ради того, чтобы что-то изменить: косметика создаст
   видимость работы и уведёт следующий круг в спор с ревьюером.
3. **Запиши разбор в файл `.verdict.md`** — по строке на замечание:
   `принято: <что и как исправил>` либо `отклонено: <почему>`. Файл обязателен
   даже когда всё отклонено: молчаливое «ничего не изменилось» неотличимо от
   сломанного прогона.
4. **Тесты.** Прогоняй проверки проекта; красный код в PR не отдаём.
5. **Коммитить самому не надо** — коммит и пуш делает контур после тебя.
"""


def round_comment(pr_number: int, *, round_number: int, max_rounds_: int,
                  verdict: str = "") -> str:
    # Команда ПЕРВОЙ строкой — это не оформление, а условие срабатывания:
    # перепроверка запускается по `startsWith(comment.body, '/review')`, той же
    # конвенцией, что и команды в Issue (`shared/commands.parse_command`).
    # Команда в конце текста читается человеком как просьба, а автоматикой — никак:
    # круг вносил правки и ждал ревью, которое не начиналось.
    body = (f"{REVIEW_COMMAND}\n\n"
            f"🔧 Внёс правки по замечаниям ревью (круг {round_number} из "
            f"{max_rounds_}) и прошу перепроверить.")
    if verdict.strip():
        body += ("\n\n<details><summary>Разбор замечаний</summary>\n\n"
                 f"{verdict.strip()}\n\n</details>")
    return body


def settled_comment(round_number: int, verdict: str = "",
                    blocked: bool | None = False) -> str:
    """Итог: правок не потребовалось. Разбор публикуется вместе с итогом.

    Без разбора этот комментарий означал бы «мы ничего не сделали, поверьте на
    слово». С ним видно, какие замечания отклонены и почему, — и следующий круг
    не начнёт спорить о том же заново.

    `blocked` — стоит ли на PR ревью, запрещающее слияние. `True` — про
    готовность не говорим вовсе: на #172 контур дважды объявил PR готовым, а
    слияние было заблокировано замечанием человека. `None` — состояние
    неизвестно, и обещать тоже нечего.
    """
    body = (
        "✅ Круг правок завершён: агент не нашёл в ревью того, что требует "
        f"изменений в коде (кругов пройдено: {round_number}).\n\n"
    )
    if blocked is True:
        body += ("На PR стоят замечания, запрещающие слияние. Снять их может "
                 "только их автор — решение за человеком.")
    elif blocked is False:
        body += "PR готов к слиянию и ждёт решения разработчика."
    else:
        body += "Состояние ревью узнать не удалось — проверьте PR перед слиянием."
    if verdict.strip():
        body += ("\n\n<details><summary>Разбор замечаний</summary>\n\n"
                 f"{verdict.strip()}\n\n</details>")
    return body


def exhausted_comment(max_rounds_: int, rounds_done: int | None = None) -> str:
    """Итог, когда довести не удалось.

    Пройденное и потолок — разные числа, и путать их нельзя. Сообщение печатало
    потолок, и оборвавшийся первый круг выглядел как три круга спора с ревьюером:
    человек шёл разбирать то, чего не было. Меньше потолка означает, что круг
    сорвался, — и об этом надо сказать прямо.
    """
    done = max_rounds_ if rounds_done is None else rounds_done
    if done < max_rounds_:
        return (
            f"⚠️ Доведение остановлено: круг правок сорвался (пройдено {done} из "
            f"{max_rounds_}).\n\n"
            "Дальше нужен человек. Замечания ревью остались в силе, но исправить "
            "их контур не смог — сорвался сам прогон, а не согласие с ревьюером. "
            "Причина — в логе воркера по этой задаче."
        )
    return (
        f"⚠️ Доведение остановлено: пройдено {max_rounds_} кругов правок, а "
        "замечания продолжают появляться.\n\n"
        "Дальше нужен человек. Столько кругов — это уже не придирки ревьюера: так "
        "выглядит проблема в самом коде или в том, как устроен репозиторий, и "
        "лечится она разбором, а не следующим кругом. Что именно осталось — в "
        "последнем комментарии ревьюера."
    )