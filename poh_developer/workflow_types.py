"""Типы, которые едут через границу репозиториев.

Стадия живёт отдельным пакетом, а её воркфлоу — дочерние прогоны цикла, который
живёт в `poh-issue-agents`. Значит эти dataclass'ы не просто типы, а **формат
сообщения** между двумя репозиториями: Temporal сериализует их в историю
прогона и восстанавливает при реплее.

Отсюда правило, которое дороже всего нарушить: **два совпадающих объявления по
разные стороны границы недопустимы.** При несовпадении числа полей Temporal не
падает, а молча отдаёт словари вместо объектов — отказ, который проявится
далеко от причины. Поэтому объявление ровно одно, здесь, а `poh-issue-agents`
переэкспортирует его из `shared/workflow_types.py`, чтобы все 66 его файлов
продолжали писать привычный `from shared.workflow_types import IssueInput`.

Форму `IssueInput` менять нельзя без разбора: `IssueDevelopment` — durable, и в
историях идущих прогонов лежит именно она.
"""

from dataclasses import dataclass


@dataclass
class IssueInput:
    """Issue, взятый циклом в работу.

    Объявлен ЗДЕСЬ, хотя принадлежит циклу задачи, а не стадии: его возит
    дочерний воркфлоу стадии, и второе объявление на той стороне дало бы ровно
    ту тихую подмену объектов словарями, о которой сказано в шапке модуля.
    `poh-issue-agents` переэкспортирует его одной строкой.
    """
    repo: str
    issue_number: int
    title: str
    body: str
    author_login: str
    author_type: str  # "Bot" | "User" | ...
    interactive: bool = True  # False in batch backfill: VAGUE escalates, no wait


@dataclass
class DevelopPlan:
    """Решения, принятые на входе в разработку, — один раз на стадию.

    Режим и ветка аналитики определяются активностью, а не воркфлоу: и то и
    другое читается из окружения и из GitHub, а решение воркфлоу обязано быть
    детерминированным при реплее. Результат активности лежит в истории, поэтому
    повтор возьмёт то же значение, что и первый прогон.
    """
    mode: str    # "local" | "dispatch" (`poh_developer/develop.py`)
    branch: str  # ветка артефактов аналитики; "" — аналитики не было
    # Сколько раз агент пробует починить своё. Умолчание 1: второй заход
    # удваивает худший случай прогона (агент идёт до 45 минут). Поднимать
    # стоит, когда наберётся статистика, сколько починок удаётся.
    repair_rounds: int = 1


@dataclass
class Diagnosis:
    """Разбор красного прогона тестов.

    `parsed=False` — исход не разобран (отчёта нет, он битый, тестов ноль,
    базовый прогон не состоялся). Тогда `own` и `foreign` пусты и смысла не
    несут: решать по ним нельзя, контур обязан вести себя как прежде.
    """
    parsed: bool
    baseline: list[str]
    own: list[str]
    foreign: list[str]
