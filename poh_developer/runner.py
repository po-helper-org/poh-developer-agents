"""Инварианты образа агента разработки — то, с чем обязан совпадать чужой образ.

Отдельным модулем, а не строками в `develop.py`, по двум причинам сразу.

Первая — `develop.py` пока побайтовая копия `shared/develop.py` из
`poh-issue-agents`, и сверка расхождения (`scripts/drift.sh`) считает любое
отличие сигналом «догнать источник». Дописать сюда константу значило бы
сломать сверку ради одной строки.

Вторая важнее и переживёт слияние копий. Здесь объявлено не то, как устроен
прогон, а то, **в чём образ раннера обязан совпасть с образом воркера** — а
воркер живёт в другом репозитории. Это контракт между двумя образами, и у него
должно быть одно имя, на которое ссылаются обе стороны.

Раньше инвариант держался тестом, сверявшим два Dockerfile в одном
репозитории. После разъезда сверять там нечего: `poh-issue-agents` сверяет свой
образ с этими константами.
"""

